#!/usr/bin/env bash
# Writes .env for THIS checkout. Every port and name comes from SLOT, so checkouts
# (yours or an agent's) never collide.
#
#   scripts/dev-env.sh [slot 0-9]     # slot defaults to the .slot file, then 0
#
# Slot 0 → web 5173, api 4001, pg 5432, redis 6379   (reserved for you)
# Slot N → each port + N*10                           (agents: 1-9)
#
# DB host: Postgres/Redis always run on the host via infra/compose.yml. Inside a
# container (an OpenHands sandbox) the host is reachable as host.docker.internal,
# so that is detected automatically. Override with DB_HOST=...
set -euo pipefail

cd "$(dirname "$0")/.."
SLOT="${1:-$(cat .slot 2>/dev/null || echo 0)}"
[[ "$SLOT" =~ ^[0-9]$ ]] || { echo "slot must be 0-9" >&2; exit 1; }

if [[ -z "${DB_HOST:-}" ]]; then
  if [[ -f /.dockerenv ]] || grep -qsE 'docker|containerd' /proc/1/cgroup; then
    DB_HOST=host.docker.internal
  else
    DB_HOST=localhost
  fi
fi

OFF=$((SLOT * 10))
# Derived from the slot (not the folder name) so it is identical on the host and
# inside a sandbox, where the checkout is mounted under a different path.
NAME="mt-s$SLOT"

PG_PORT=$((5432 + OFF))
REDIS_PORT=$((6379 + OFF))
API_PORT=$((4001 + OFF))   # not 3001: OpenHands Agent Canvas uses it
WEB_PORT=$((5173 + OFF))

cat > .env <<EOF
# Generated by scripts/dev-env.sh — do not commit.
SLOT=$SLOT
COMPOSE_PROJECT_NAME=$NAME

PG_PORT=$PG_PORT
REDIS_PORT=$REDIS_PORT
API_PORT=$API_PORT
WEB_PORT=$WEB_PORT

DATABASE_URL=postgresql://postgres:dev@$DB_HOST:$PG_PORT/mortgage
REDIS_URL=redis://$DB_HOST:$REDIS_PORT
VITE_API_URL=http://localhost:$API_PORT
EOF

# Inside a sandbox nobody can answer prompts (an OpenHands terminal still looks
# like a TTY). CI=true makes Prisma & co. fail or use defaults instead of hanging.
if [[ "$DB_HOST" == "host.docker.internal" ]]; then
  printf '\n# Sandbox: never wait for interactive input.\nCI=true\n' >> .env
fi

echo "wrote .env (slot $SLOT, db host $DB_HOST): web :$WEB_PORT, api :$API_PORT, pg :$PG_PORT, redis :$REDIS_PORT"
