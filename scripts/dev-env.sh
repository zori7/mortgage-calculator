#!/usr/bin/env bash
# Writes .env for THIS worktree. Every port and name comes from SLOT, so worktrees
# (yours or an agent's) never collide.
#
#   scripts/dev-env.sh <slot 0-9>
#
# Slot 0 → web 5173, api 3001, pg 5432, redis 6379
# Slot N → each port + N*10
#
# DB_HOST (default localhost): set it to host.docker.internal when the app runs
# inside a sandbox (OpenHands) but Postgres/Redis run on the host.
set -euo pipefail

SLOT="${1:?usage: scripts/dev-env.sh <slot 0-9>}"
[[ "$SLOT" =~ ^[0-9]$ ]] || { echo "slot must be 0-9" >&2; exit 1; }

cd "$(dirname "$0")/.."
OFF=$((SLOT * 10))
NAME="mt-$(basename "$PWD" | tr -c 'a-zA-Z0-9\n' '-' | tr 'A-Z' 'a-z')"
HOST="${DB_HOST:-localhost}"

PG_PORT=$((5432 + OFF))
REDIS_PORT=$((6379 + OFF))
API_PORT=$((3001 + OFF))
WEB_PORT=$((5173 + OFF))

cat > .env <<EOF
# Generated by scripts/dev-env.sh $SLOT — do not commit.
SLOT=$SLOT
COMPOSE_PROJECT_NAME=$NAME

PG_PORT=$PG_PORT
REDIS_PORT=$REDIS_PORT
API_PORT=$API_PORT
WEB_PORT=$WEB_PORT

DATABASE_URL=postgresql://postgres:dev@$HOST:$PG_PORT/mortgage
REDIS_URL=redis://$HOST:$REDIS_PORT
VITE_API_URL=http://localhost:$API_PORT
EOF

echo "wrote .env (slot $SLOT, project $NAME): web :$WEB_PORT, api :$API_PORT, pg :$PG_PORT, redis :$REDIS_PORT"
